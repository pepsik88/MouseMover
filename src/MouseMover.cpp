// ============================================================
// Parse HH:MM
// ============================================================

bool ParseTime(
    const std::wstring& value,
    int& minutes)
{
    if (value.size() != 5)
        return false;

    if (value[2] != L':')
        return false;

    for (int index : {0, 1, 3, 4})
    {
        if (value[index] < L'0' ||
            value[index] > L'9')
        {
            return false;
        }
    }

    int hour =
        (value[0] - L'0') * 10 +
        (value[1] - L'0');

    int minute =
        (value[3] - L'0') * 10 +
        (value[4] - L'0');

    if (hour > 23 ||
        minute > 59)
    {
        return false;
    }

    minutes =
        hour * 60 + minute;

    return true;
}


// ============================================================
// Check active time
// ============================================================

bool IsActiveTime()
{
    if (!IsTodayEnabled())
        return false;

    int startMinutes;
    int endMinutes;

    if (!ParseTime(
            GetControlText(g_startTime),
            startMinutes))
    {
        return false;
    }

    if (!ParseTime(
            GetControlText(g_endTime),
            endMinutes))
    {
        return false;
    }

    SYSTEMTIME systemTime{};

    GetLocalTime(
        &systemTime
    );

    int currentMinutes =
        systemTime.wHour * 60 +
        systemTime.wMinute;

    // Same start/end means 24 hours.
    if (startMinutes == endMinutes)
        return true;

    // Normal interval, e.g. 08:00 - 16:30.
    if (startMinutes < endMinutes)
    {
        return
            currentMinutes >= startMinutes &&
            currentMinutes < endMinutes;
    }

    // Overnight interval, e.g. 22:00 - 06:00.
    return
        currentMinutes >= startMinutes ||
        currentMinutes < endMinutes;
}


