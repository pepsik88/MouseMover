void CleanupDiagnosticLog()
{
    std::filesystem::path p(GetSettingsPath());
    p = p.parent_path() / L"MouseMover.log";

    if (!std::filesystem::exists(p))
        return;

    std::wifstream in(p);
    if (!in)
        return;

    std::vector<std::wstring> kept;
    std::wstring line;

    const std::time_t now = std::time(nullptr);
    const std::time_t cutoff = now - (30LL * 24LL * 60LL * 60LL);

    while (std::getline(in, line))
    {
        // New format: YYYY-MM-DD HH:MM:SS  message
        if (line.size() >= 19 &&
            line[4] == L'-' &&
            line[7] == L'-' &&
            line[10] == L' ')
        {
            std::tm tm{};
            try
            {
                tm.tm_year = std::stoi(line.substr(0, 4)) - 1900;
                tm.tm_mon  = std::stoi(line.substr(5, 2)) - 1;
                tm.tm_mday = std::stoi(line.substr(8, 2));
                tm.tm_hour = std::stoi(line.substr(11, 2));
                tm.tm_min  = std::stoi(line.substr(14, 2));
                tm.tm_sec  = std::stoi(line.substr(17, 2));
                tm.tm_isdst = -1;

                std::time_t t = std::mktime(&tm);
                if (t != static_cast<std::time_t>(-1) && t >= cutoff)
                    kept.push_back(line);
            }
            catch (...)
            {
                // Preserve malformed lines rather than deleting them accidentally.
                kept.push_back(line);
            }
        }
        else
        {
            // Legacy entries have only HH:MM:SS and no date, so their age
            // cannot be determined safely. Preserve them.
            kept.push_back(line);
        }
    }
    in.close();

    std::filesystem::path tmp = p;
    tmp += L".tmp";

    {
        std::wofstream output(tmp, std::ios::trunc);
        if (!output)
            return;

        for (const auto& keptLine : kept)
            output << keptLine << L"\n";
    }

    std::error_code ec;
    std::filesystem::rename(tmp, p, ec);
    if (ec)
    {
        std::filesystem::remove(p, ec);
        ec.clear();
        std::filesystem::rename(tmp, p, ec);
        if (ec)
            std::filesystem::remove(tmp, ec);
    }
}


