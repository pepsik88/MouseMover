void UpdateLanguage()
{
    if (!g_hwnd)
        return;

    HWND child = GetWindow(g_hwnd, GW_CHILD);

    while (child)
    {
        wchar_t current[256]{};
        GetWindowTextW(child, current, 256);
        std::wstring value = current;

        if (value == L"Zapnout:" || value == L"Start:")
            SetWindowTextW(child, T(L"Zapnout:", L"Start:"));
        else if (value == L"Vypnout:" || value == L"Stop:")
            SetWindowTextW(child, T(L"Vypnout:", L"Stop:"));
        else if (value == L"Interval (sekundy):" ||
                 value == L"Interval (seconds):")
            SetWindowTextW(child, T(L"Interval (sekundy):", L"Interval (seconds):"));
        else if (value == L"Pohyb (pixely):" ||
                 value == L"Movement (pixels):")
            SetWindowTextW(child, T(L"Pohyb (pixely):", L"Movement (pixels):"));
        else if (value == L"Spustit automaticky s Windows" ||
                 value == L"Start automatically with Windows")
            SetWindowTextW(child, T(
                L"Spustit automaticky s Windows",
                L"Start automatically with Windows"));
        else if (value == L"Minimalizovat do system tray" ||
                 value == L"Minimize to system tray")
            SetWindowTextW(child, T(
                L"Minimalizovat do system tray",
                L"Minimize to system tray"));

        child = GetWindow(child, GW_HWNDNEXT);
    }

    if (g_languageButton)
        SetWindowTextW(g_languageButton, g_english ? L"\u010Ce\u0161tina" : L"English");

    if (g_scheduleTitleUi)
        SetWindowTextW(g_scheduleTitleUi,
            g_matrixTheme ? T(L"[ PLÁN ]", L"[ SCHEDULE ]")
                          : T(L"Plán", L"Schedule"));

    if (g_movementTitleUi)
        SetWindowTextW(g_movementTitleUi,
            g_matrixTheme ? T(L"[ POHYB ]", L"[ MOVEMENT ]")
                          : T(L"Pohyb", L"Movement"));

    if (g_windowsTitleUi)
        SetWindowTextW(g_windowsTitleUi,
            g_matrixTheme ? T(L"[ WINDOWS ]", L"[ WINDOWS ]")
                          : L"Windows");

    if (g_testButtonUi)
        SetWindowTextW(g_testButtonUi,
            g_matrixTheme ? L"[ TEST ]"
                          : T(L"TEST POHYBU", L"TEST MOVEMENT"));
    if(g_preventSleepUi) SetWindowTextW(g_preventSleepUi,T(L"Zabránit uspání PC",L"Prevent PC sleep"));
    if(g_keepDisplayUi) SetWindowTextW(g_keepDisplayUi,T(L"Nechat displej zapnutý",L"Keep display on"));
    if(g_pauseFullscreenUi) SetWindowTextW(g_pauseFullscreenUi,T(L"Pozastavit ve fullscreen",L"Pause on fullscreen"));
    if(g_loggingUi) SetWindowTextW(g_loggingUi,T(L"Diagnostický log",L"Diagnostic log"));
    if(g_aboutUi) SetWindowTextW(g_aboutUi,
        g_matrixTheme ? L"[ INFO ]" : T(L"O PROGRAMU",L"ABOUT"));
    if(g_openLogUi) SetWindowTextW(g_openLogUi,
        g_matrixTheme ? L"[ LOG ]" : T(L"OTEVŘÍT LOG",L"OPEN LOG"));
    const wchar_t* dc[7]={L"Po",L"Út",L"St",L"Čt",L"Pá",L"So",L"Ne"};
    const wchar_t* de[7]={L"Mo",L"Tu",L"We",L"Th",L"Fr",L"Sa",L"Su"};
    for(int i=0;i<7;++i) if(g_dayChecks[i]) SetWindowTextW(g_dayChecks[i],g_english?de[i]:dc[i]);
    if (g_themeUi)
        SetWindowTextW(
            g_themeUi,
            g_matrixTheme
                ? T(L"KLASICKÝ", L"CLASSIC")
                : L"MATRIX"
        );

    UpdateStats();

    UpdateKeepAwakeIndicator();
    UpdateLastActivityLabel();

    if (g_status)
    {
        wchar_t s[256]{};
        GetWindowTextW(g_status, s, 256);
        std::wstring value = s;

        if (value.find((g_matrixTheme ? L"> SYSTEM STOPPED <" : T(L"VYPNUTO", L"STOPPED"))) == 0 || value.find(L"STOPPED") == 0)
            SetWindowTextW(g_status, (g_matrixTheme ? L"> SYSTEM STOPPED <" : T(L"VYPNUTO", L"STOPPED")));
        else if ((value.find(L"MIMO CAS") == 0 || value.find(L"MIMO ČAS") == 0 || value.find(L"OUTSIDE HOURS") == 0 || value.find(L"OUTSIDE ACTIVE TIME") == 0))
            SetWindowTextW(g_status, T(L"MIMO ČAS - čekám", L"OUTSIDE HOURS - waiting"));
        else if ((value.find(L"PSANI") == 0 || value.find(L"PSANÍ") == 0 || value.find(L"TYPING") == 0))
            SetWindowTextW(g_status, T(L"PSANÍ - odpočet resetován", L"TYPING - countdown reset"));
        else if (value.find(L"POHYB MYŠI") == 0 || value.find(L"MOUSE MOVEMENT") == 0)
            SetWindowTextW(g_status, T(L"POHYB MYŠI - odpočet resetován", L"MOUSE MOVEMENT - countdown reset"));
        else if ((value.find(L"AKTIVITA UZIVATELE") == 0 || value.find(L"AKTIVITA UŽIVATELE") == 0 || value.find(L"USER ACTIVITY") == 0))
            SetWindowTextW(g_status, T(L"AKTIVITA UŽIVATELE - odpočet resetován", L"USER ACTIVITY - countdown reset"));
        else if ((value.find(L"AKTIVNI - pohybuji") == 0 || value.find(L"AKTIVNÍ - pohybuji") == 0 || value.find(L"ACTIVE - moving") == 0))
            SetWindowTextW(g_status, T(L"AKTIVNÍ • pohybuji kurzorem", L"ACTIVE • moving cursor"));
        else if ((value.find(L"AKTIVNI - cekam") == 0 || value.find(L"AKTIVNÍ - čekám") == 0 || value.find(L"ACTIVE - waiting") == 0))
            SetWindowTextW(g_status, (g_matrixTheme ? L"> SYSTEM ACTIVE <" : T(L"AKTIVNÍ", L"ACTIVE")));
    }

    if (g_countdown)
    {
        wchar_t c[256]{};
        GetWindowTextW(g_countdown, c, 256);
        std::wstring value = c;
        size_t pos = value.find(L':');

        if (pos != std::wstring::npos &&
            (value.find(L"Další pohyb za:") == 0 ||
             value.find(L"Next movement in:") == 0))
        {
            SetWindowTextW(
                g_countdown,
                (std::wstring(T(L"Další pohyb za:", L"Next movement in:")) +
                 value.substr(pos + 1)).c_str()
            );
        }
    }
}


