// Matrix animated background -------------------------------------------------
// The animation is drawn only by the main window. Child controls keep their
// own readable backgrounds, so the falling code stays decorative and does not
// reduce usability.
static const UINT_PTR TIMER_MATRIX_RAIN = 9002;
static const UINT MATRIX_RAIN_MS = 120;

struct MatrixRainColumn
{
    int x = 0;
    int y = 0;
    int speed = 1;
    int length = 10;
    unsigned seed = 1;
};

static std::vector<MatrixRainColumn> g_matrixRain;
static int g_matrixRainWidth = 0;
static int g_matrixRainHeight = 0;

static wchar_t MatrixRainGlyph(unsigned value)
{
    // ASCII/code-like glyphs are intentionally used because Consolas is
    // guaranteed to render them consistently on normal Windows installs.
    static const wchar_t glyphs[] =
        L"01ABCDEFGHIJKLMNOPQRSTUVWXYZ<>[]{}+-=*/\\|:;#$%&@";
    return glyphs[value % (sizeof(glyphs) / sizeof(glyphs[0]) - 1)];
}

static void ResetMatrixRain(HWND hwnd)
{
    if (!hwnd) return;

    RECT rc{};
    GetClientRect(hwnd, &rc);
    g_matrixRainWidth = rc.right - rc.left;
    g_matrixRainHeight = rc.bottom - rc.top;

    const int spacing = 18;
    const int count = std::max(1, g_matrixRainWidth / spacing + 1);
    g_matrixRain.clear();
    g_matrixRain.reserve(count);

    unsigned seed = static_cast<unsigned>(GetTickCount());
    for (int i = 0; i < count; ++i)
    {
        seed = seed * 1664525u + 1013904223u;
        MatrixRainColumn c;
        c.x = i * spacing + static_cast<int>((seed >> 24) % 7) - 3;
        c.y = -static_cast<int>((seed >> 8) % std::max(80, g_matrixRainHeight));
        c.speed = 4 + static_cast<int>((seed >> 16) % 8);
        c.length = 7 + static_cast<int>((seed >> 20) % 15);
        c.seed = seed ^ static_cast<unsigned>(i * 2654435761u);
        g_matrixRain.push_back(c);
    }
}

static void AdvanceMatrixRain(HWND hwnd)
{
    if (!g_matrixTheme || !hwnd) return;
    if (g_matrixRain.empty()) ResetMatrixRain(hwnd);

    for (auto& c : g_matrixRain)
    {
        c.y += c.speed;
        c.seed = c.seed * 1664525u + 1013904223u;
        if (c.y - c.length * 17 > g_matrixRainHeight)
        {
            c.y = -20 - static_cast<int>((c.seed >> 8) % 260);
            c.speed = 4 + static_cast<int>((c.seed >> 16) % 8);
            c.length = 7 + static_cast<int>((c.seed >> 20) % 15);
        }
    }
}

static void DrawMatrixRain(HDC hdc, const RECT& rc)
{
    HBRUSH black = CreateSolidBrush(RGB(2, 7, 4));
    FillRect(hdc, &rc, black);
    DeleteObject(black);

    if (g_matrixRain.empty()) ResetMatrixRain(g_hwnd);

    HFONT oldFont = nullptr;
    if (g_fontMatrix)
        oldFont = reinterpret_cast<HFONT>(SelectObject(hdc, g_fontMatrix));
    SetBkMode(hdc, TRANSPARENT);

    const int step = 17;
    for (const auto& c : g_matrixRain)
    {
        for (int i = 0; i < c.length; ++i)
        {
            const int y = c.y - i * step;
            if (y < -step || y > rc.bottom) continue;

            // Bright head, then a progressively darker green tail.
            int green = 230 - (i * 180 / std::max(1, c.length - 1));
            int red = (i == 0) ? 190 : 0;
            int blue = (i == 0) ? 190 : 25;
            SetTextColor(hdc, RGB(red, std::max(45, green), blue));

            wchar_t text[2] = {
                MatrixRainGlyph(c.seed + static_cast<unsigned>(i * 37 + c.x)),
                0
            };
            TextOutW(hdc, c.x, y, text, 1);
        }
    }

    if (oldFont) SelectObject(hdc, oldFont);
}

