// ============================================================
// Move cursor
// ============================================================

void MoveCursor()
{
    POINT originalPosition{};

    if (!GetCursorPos(&originalPosition))
        return;

    // "Pohyb (pixely)" is the maximum/target distance of the
    // temporary random movement.
    int pixels =
        ReadNumber(
            g_pixels,
            5,
            1,
            500
        );

    // Generate a random direction.
    //
    // The cursor is moved by the configured number of pixels
    // in a random direction and then returned to the exact
    // original position.

    static std::random_device randomDevice;
    static std::mt19937 randomGenerator(randomDevice());

    std::uniform_real_distribution<double> angleDistribution(
        0.0,
        2.0 * 3.14159265358979323846
    );

    double angle =
        angleDistribution(randomGenerator);

    int deltaX =
        static_cast<int>(
            std::lround(
                std::cos(angle) * pixels
            )
        );

    int deltaY =
        static_cast<int>(
            std::lround(
                std::sin(angle) * pixels
            )
        );

    // For very small pixel values it is theoretically possible
    // for rounding to produce 0/0. Make sure the cursor really
    // moves.

    if (deltaX == 0 && deltaY == 0)
    {
        deltaX = pixels;
    }

    // --------------------------------------------------------
    // Move to the random position.
    // --------------------------------------------------------

    SetCursorPos(
        originalPosition.x + deltaX,
        originalPosition.y + deltaY
    );

    // Give Windows a short moment to process the mouse movement.
    Sleep(50);

    // --------------------------------------------------------
    // Return to the exact original position.
    // --------------------------------------------------------

    SetCursorPos(
        originalPosition.x,
        originalPosition.y
    );

    Sleep(20);
}


// ============================================================
// Worker thread
// ============================================================

void WorkerThread()
{
    POINT lastPosition{};

    GetCursorPos(
        &lastPosition
    );

    int remaining =
        ReadNumber(
            g_interval,
            30,
            1,
            86400
        );

    PostCountdown(
        remaining
    );

    while (g_running)
    {

        UserActivityKind activity = DetectUserActivity();

        if (activity == UserActivityKind::Mouse)
        {
            RecordActivity(L"Pohyb myši", L"Mouse movement");
            ++g_resets;
            UpdateStats();
            remaining =
                ReadNumber(
                    g_interval,
                    30,
                    1,
                    86400
                );

            PostCountdown(
                remaining
            );
            PostStatus(T(
                L"POHYB MYŠI - detekován",
                L"MOUSE MOVEMENT - detected"
            ));
        }
        else if (activity == UserActivityKind::Keyboard)
        {
            RecordActivity(L"Klávesnice", L"Keyboard");
            ++g_resets;
            UpdateStats();
            remaining =
                ReadNumber(
                    g_interval,
                    30,
                    1,
                    86400
                );

            PostCountdown(
                remaining
            );
            PostStatus(T(
                L"PSANÍ - odpočet resetován",
                L"TYPING - countdown reset"
            ));
        }

        // ----------------------------------------------------
        // Outside configured time
        // ----------------------------------------------------

        if (!IsActiveTime())
        {
            PostStatus(
                T(L"MIMO ČAS - čekám", L"OUTSIDE HOURS - waiting")
            );

            PostCountdown(
                -1
            );
        }
        else
        {
            int interval =
                ReadNumber(
                    g_interval,
                    30,
                    1,
                    86400
                );

            if (remaining > interval)
            {
                remaining =
                    interval;
            }


            // ------------------------------------------------
            // Detect USER mouse movement
            // ------------------------------------------------

            POINT currentPosition{};

            if (GetCursorPos(
                    &currentPosition))
            {
                if (currentPosition.x != lastPosition.x ||
                    currentPosition.y != lastPosition.y)
                {
                    // User moved the mouse.
                    //
                    // Reset the complete interval.

                    remaining =
                        interval;

                    lastPosition =
                        currentPosition;

                    PostStatus(
                        T(L"POHYB MYŠI - odpočet resetován", L"MOUSE MOVEMENT - countdown reset")
                    );
                }
                else if (remaining <= 0)
                {
                    // Show 00:00 before the automatic movement.
                    PostCountdown(0);
                    UpdateWindow(g_countdown);

                    // ------------------------------------------------
                    // Automatic mouse movement
                    // ------------------------------------------------

                    PostStatus(
                        T(L"AKTIVNÍ • pohybuji kurzorem", L"ACTIVE • moving cursor")
                    );

                    MoveCursor();
                    ++g_autoMoves;
                    UpdateStats();
                    WriteLog(T(L"Automatický pohyb kurzoru", L"Automatic cursor movement"));

                    // Save new cursor position immediately.
                    //
                    // This prevents our own movement from being
                    // detected as user movement.

                    GetCursorPos(
                        &lastPosition
                    );

                    remaining =
                        interval;
                }
                else
                {
                    PostStatus(
                        (g_matrixTheme ? L"> SYSTEM ACTIVE <" : T(L"AKTIVNÍ", L"ACTIVE"))
                    );
                }
            }

            PostCountdown(
                remaining
            );
        }


        // ----------------------------------------------------
        // Interruptible one-second wait
        //
        // Stop() calls notify_all(), therefore this wait is
        // interrupted immediately instead of waiting the whole
        // interval.
        // ----------------------------------------------------

        std::unique_lock<std::mutex> lock(
            g_mutex
        );

        bool stopped =
            g_cv.wait_for(
                lock,
                std::chrono::seconds(1),
                []()
                {
                    return !g_running.load();
                }
            );

        if (stopped)
            break;


        // ----------------------------------------------------
        // Update countdown
        // ----------------------------------------------------

        if (IsActiveTime())
        {
            if (remaining > 0)
                --remaining;
        }
        else
        {
            remaining =
                ReadNumber(
                    g_interval,
                    30,
                    1,
                    86400
                );
        }
    }


    PostCountdown(
        -1
    );

    PostStatus(
        (g_matrixTheme ? L"> SYSTEM STOPPED <" : T(L"VYPNUTO", L"STOPPED"))
    );
}


// ============================================================
// Windows power management
// ============================================================

void SetKeepAwake(bool enabled)
{
    if (enabled)
    {
        EXECUTION_STATE flags = ES_CONTINUOUS;
        if (!g_preventSleepUi || IsChecked(IDC_PREVENT_SLEEP))
            flags = static_cast<EXECUTION_STATE>(flags | ES_SYSTEM_REQUIRED);
        if (!g_keepDisplayUi || IsChecked(IDC_KEEP_DISPLAY))
            flags = static_cast<EXECUTION_STATE>(flags | ES_DISPLAY_REQUIRED);
        SetThreadExecutionState(flags);
    }
    else
    {
        // Clear our continuous execution-state request.
        SetThreadExecutionState(
            ES_CONTINUOUS
        );
    }
}


// ============================================================
// Windows autostart
// ============================================================

void SetAutoStart(
    bool enabled)
{
    HKEY key{};

    LONG result =
        RegOpenKeyExW(
            HKEY_CURRENT_USER,
            L"Software\\Microsoft\\Windows\\CurrentVersion\\Run",
            0,
            KEY_SET_VALUE,
            &key
        );

    if (result != ERROR_SUCCESS)
        return;


    if (enabled)
    {
        wchar_t executable[MAX_PATH]{};

        GetModuleFileNameW(
            nullptr,
            executable,
            MAX_PATH
        );

        std::wstring command =
            L"\"" +
            std::wstring(executable) +
            L"\"";

        RegSetValueExW(
            key,
            L"MouseMover",
            0,
            REG_SZ,
            reinterpret_cast<const BYTE*>(
                command.c_str()
            ),
            static_cast<DWORD>(
                (command.size() + 1) *
                sizeof(wchar_t)
            )
        );
    }
    else
    {
        RegDeleteValueW(
            key,
            L"MouseMover"
        );
    }

    RegCloseKey(
        key
    );
}


// ============================================================
// Add system tray icon
// ============================================================

void AddTrayIcon()
{
    if (!g_hwnd)
        return;


    // If an old icon exists, remove it first.
    if (g_nid.hWnd != nullptr)
    {
        Shell_NotifyIconW(
            NIM_DELETE,
            &g_nid
        );
    }


    ZeroMemory(
        &g_nid,
        sizeof(g_nid)
    );


    g_nid.cbSize =
        sizeof(NOTIFYICONDATAW);

    g_nid.hWnd =
        g_hwnd;

    g_nid.uID =
        1;

    g_nid.uFlags =
        NIF_MESSAGE |
        NIF_ICON |
        NIF_TIP;

    g_nid.uCallbackMessage =
        WM_TRAYICON;


    g_nid.hIcon =
        LoadIconW(
            GetModuleHandleW(nullptr),
            MAKEINTRESOURCEW(1)
        );


    if (!g_nid.hIcon)
    {
        g_nid.hIcon =
            LoadIconW(
                nullptr,
                IDI_APPLICATION
            );
    }


    wcscpy_s(
        g_nid.szTip,
        L"Mouse Mover"
    );


    BOOL added =
        Shell_NotifyIconW(
            NIM_ADD,
            &g_nid
        );

    if (!added)
    {
        // Do not leave a seemingly registered tray state when Windows
        // rejected the notification icon.
        ZeroMemory(
            &g_nid,
            sizeof(g_nid)
        );
        return;
    }


    // Keep the classic tray callback behavior.
    // lParam then contains the mouse event directly.
    UpdateTrayIconForState();
}


// ============================================================
// Remove system tray icon
// ============================================================

void RemoveTrayIcon()
{
    if (g_nid.hWnd != nullptr)
    {
        Shell_NotifyIconW(
            NIM_DELETE,
            &g_nid
        );
    }

    ZeroMemory(
        &g_nid,
        sizeof(g_nid)
    );
}


// ============================================================
// Refresh tray icon
//
// This is important after Windows Explorer restarts.
// ============================================================

void RefreshTrayIcon()
{
    if (!g_hwnd)
        return;


    if (g_nid.hWnd == nullptr)
    {
        AddTrayIcon();
        return;
    }


    if (!Shell_NotifyIconW(
            NIM_MODIFY,
            &g_nid))
    {
        // Explorer probably restarted and forgot our icon.
        AddTrayIcon();
    }
}


// ============================================================
// Start application
// ============================================================

void StartApplication()
{
    if (g_running)
        return;


    if (!ValidateSettings(true))
        return;

    int dummy;


    if (!ParseTime(
            GetControlText(g_startTime),
            dummy) ||
        !ParseTime(
            GetControlText(g_endTime),
            dummy))
    {
        MessageBoxW(
            g_hwnd,
            L"Čas musí být ve formátu HH:MM.\n\n"
            L"Příklad:\n"
            L"08:00\n"
            L"16:30",
            L"Mouse Mover",
            MB_ICONERROR
        );

        return;
    }


    g_running =
        true;

    g_autoMoves = 0;
    g_resets = 0;
    GetLocalTime(&g_startedAt);
    UpdateStats();
    WriteLog(T(L"START", L"START"));

    GetCursorPos(&g_lastObservedCursor);
    g_haveLastObservedCursor = true;

    g_keyboardActivityPending.store(
        false,
        std::memory_order_relaxed
    );


    // Explicitly prevent Windows sleep/display idle while Mouse Mover is running.
    SetKeepAwake(true);
    UpdateKeepAwakeIndicator();
    UpdateTrayTooltip();


    EnableWindow(
        GetDlgItem(
            g_hwnd,
            IDC_START
        ),
        FALSE
    );


    EnableWindow(
        GetDlgItem(
            g_hwnd,
            IDC_STOP
        ),
        TRUE
    );


    SaveSettings(
        true
    );


    if (g_worker.joinable())
    {
        g_worker.join();
    }


    g_worker =
        std::thread(
            WorkerThread
        );
}


// ============================================================
// Stop application
// ============================================================

void StopApplication(
    bool saveSettings = true)
{
    g_running =
        false;

    // Allow normal Windows power management again.
    SetKeepAwake(false);
    UpdateKeepAwakeIndicator();
    WriteLog(T(L"STOP", L"STOP"));
    UpdateTrayTooltip();


    // IMPORTANT:
    // Wake the worker immediately.
    g_cv.notify_all();


    if (g_worker.joinable())
    {
        g_worker.join();
    }


    EnableWindow(
        GetDlgItem(
            g_hwnd,
            IDC_START
        ),
        TRUE
    );


    EnableWindow(
        GetDlgItem(
            g_hwnd,
            IDC_STOP
        ),
        FALSE
    );


    SetWindowTextW(
        g_status,
        (g_matrixTheme ? L"> SYSTEM STOPPED <" : T(L"VYPNUTO", L"STOPPED"))
    );


    SetWindowTextW(g_countdown, L"");


    if (saveSettings)
    {
        SaveSettings(
            false
        );
    }
}


