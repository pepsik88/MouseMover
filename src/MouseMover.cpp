HICON CreateIconFromBGRA32(const unsigned char* pixels)
{
    BITMAPV5HEADER bi{};
    bi.bV5Size = sizeof(BITMAPV5HEADER);
    bi.bV5Width = 32;
    bi.bV5Height = -32; // top-down DIB
    bi.bV5Planes = 1;
    bi.bV5BitCount = 32;
    bi.bV5Compression = BI_BITFIELDS;
    bi.bV5RedMask   = 0x00FF0000;
    bi.bV5GreenMask = 0x0000FF00;
    bi.bV5BlueMask  = 0x000000FF;
    bi.bV5AlphaMask = 0xFF000000;

    void* bits = nullptr;
    HDC hdc = GetDC(nullptr);
    HBITMAP color = CreateDIBSection(
        hdc,
        reinterpret_cast<BITMAPINFO*>(&bi),
        DIB_RGB_COLORS,
        &bits,
        nullptr,
        0
    );
    ReleaseDC(nullptr, hdc);

    if (!color || !bits)
    {
        if (color) DeleteObject(color);
        return nullptr;
    }

    memcpy(bits, pixels, 32 * 32 * 4);

    // Opaque image mask. Alpha is supplied by the 32-bit color bitmap.
    HBITMAP mask = CreateBitmap(32, 32, 1, 1, nullptr);
    if (!mask)
    {
        DeleteObject(color);
        return nullptr;
    }

    HDC maskDC = CreateCompatibleDC(nullptr);
    HGDIOBJ oldMask = SelectObject(maskDC, mask);
    PatBlt(maskDC, 0, 0, 32, 32, BLACKNESS);
    SelectObject(maskDC, oldMask);
    DeleteDC(maskDC);

    ICONINFO ii{};
    ii.fIcon = TRUE;
    ii.hbmColor = color;
    ii.hbmMask = mask;

    HICON icon = CreateIconIndirect(&ii);

    DeleteObject(color);
    DeleteObject(mask);
    return icon;
}

HICON CreateClassicTrayStateIcon(bool active)
{
    constexpr int S = 16;

    HDC screen = GetDC(nullptr);
    HDC colorDC = CreateCompatibleDC(screen);
    HDC maskDC = CreateCompatibleDC(screen);

    HBITMAP colorBmp = CreateCompatibleBitmap(screen, S, S);
    HBITMAP maskBmp = CreateBitmap(S, S, 1, 1, nullptr);

    HGDIOBJ oldColor = SelectObject(colorDC, colorBmp);
    HGDIOBJ oldMask = SelectObject(maskDC, maskBmp);

    RECT rc{0,0,S,S};
    HBRUSH bg = CreateSolidBrush(RGB(245,247,249));
    FillRect(colorDC, &rc, bg);
    DeleteObject(bg);

    PatBlt(maskDC, 0, 0, S, S, WHITENESS);

    COLORREF stateColor =
        active ? RGB(22,163,74) : RGB(220,38,38);

    HBRUSH stateBrush = CreateSolidBrush(stateColor);
    HPEN statePen = CreatePen(PS_SOLID, 1, stateColor);
    HGDIOBJ oldBrush = SelectObject(colorDC, stateBrush);
    HGDIOBJ oldPen = SelectObject(colorDC, statePen);

    Ellipse(colorDC, 2, 2, 14, 14);

    HBRUSH black = static_cast<HBRUSH>(GetStockObject(BLACK_BRUSH));
    HGDIOBJ oldMaskBrush = SelectObject(maskDC, black);
    Ellipse(maskDC, 2, 2, 14, 14);
    SelectObject(maskDC, oldMaskBrush);

    SelectObject(colorDC, oldBrush);
    SelectObject(colorDC, oldPen);
    DeleteObject(stateBrush);
    DeleteObject(statePen);

    SelectObject(colorDC, oldColor);
    SelectObject(maskDC, oldMask);
    DeleteDC(colorDC);
    DeleteDC(maskDC);
    ReleaseDC(nullptr, screen);

    ICONINFO ii{};
    ii.fIcon = TRUE;
    ii.hbmColor = colorBmp;
    ii.hbmMask = maskBmp;

    HICON icon = CreateIconIndirect(&ii);
    DeleteObject(colorBmp);
    DeleteObject(maskBmp);
    return icon;
}

void EnsureDynamicTrayIcons()
{
    if (!g_trayClassicActive)
        g_trayClassicActive = CreateClassicTrayStateIcon(true);
    if (!g_trayClassicStopped)
        g_trayClassicStopped = CreateClassicTrayStateIcon(false);

    if (!g_trayMatrixActive)
        g_trayMatrixActive = CreateIconFromBGRA32(g_matrixActivePixels);
    if (!g_trayMatrixStopped)
        g_trayMatrixStopped = CreateIconFromBGRA32(g_matrixStoppedPixels);
}

void UpdateTrayIconForState()
{
    if (!g_nid.hWnd)
        return;

    EnsureDynamicTrayIcons();

    HICON icon = nullptr;

    if (g_matrixTheme)
        icon = g_running ? g_trayMatrixActive : g_trayMatrixStopped;
    else
        icon = g_running ? g_trayClassicActive : g_trayClassicStopped;

    if (!icon)
        return;

    g_nid.hIcon = icon;
    g_nid.uFlags = NIF_ICON | NIF_MESSAGE | NIF_TIP;
    Shell_NotifyIconW(NIM_MODIFY, &g_nid);
}

